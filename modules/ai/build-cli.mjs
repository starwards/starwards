// Builds the headless training CLIs into dist/cli for many short-lived worker processes:
//
// - dist/cli/<name>.bundle.js: esbuild bundle. Workspace sources (@starwards/server/src, @starwards/core/src)
//   are bundled; every package, built workspace packages included, stays external so schema classes keep
//   one instance. JSON imports become JSON.parse of a string, which V8 parses faster than an object literal.
// - dist/cli/<name>.js: entry that turns on the V8 compile cache in dist/cli/.compile-cache and requires
//   the bundle. It sets NODE_COMPILE_CACHE, so forked workers, which fork the bundle itself, use it too.
// - dist/cli/.compile-cache: produced here by loading each bundle once, so the first run and every worker
//   start warm. Build it where it runs (same Node version, same absolute path), e.g. in the Docker image.
//
// dist/cli sits at the depth of src/cli, so __dirname-relative paths (crews, curriculum, training-archive)
// resolve alike. Benchmarks: docs/testing/headless-runtime-benchmarks.md.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import esbuild from 'esbuild';

const entries = ['train', 'branch'];
const outdir = 'dist/cli';
const cacheDir = '.compile-cache';

fs.rmSync(outdir, { recursive: true, force: true });
await esbuild.build({
    entryPoints: entries.map((e) => `src/cli/${e}.ts`),
    entryNames: '[name].bundle',
    outdir,
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node24',
    sourcemap: true,
    logLevel: 'warning',
    plugins: [
        {
            name: 'external-packages',
            setup(build) {
                build.onResolve({ filter: /^[^./]/ }, (args) =>
                    /^@starwards\/(server|core)\/src\//.test(args.path) ? undefined : { external: true },
                );
            },
        },
        {
            // the regression scorers load lazily (`scorers` in src/scoring/score.ts); keeping them out of
            // the bundle spares every worker parsing 6 MB of source it never runs
            name: 'lazy-scorers',
            setup(build) {
                build.onResolve({ filter: /^\.\/models\/v[123]\.json$/ }, (args) => ({
                    path: `../../src/scoring/models/${path.basename(args.path)}`,
                    external: true,
                }));
            },
        },
        {
            name: 'json-parse',
            setup(build) {
                build.onLoad({ filter: /\.json$/ }, (args) => ({
                    contents: `module.exports = JSON.parse(${JSON.stringify(fs.readFileSync(args.path, 'utf8'))});`,
                    loader: 'js',
                }));
            },
        },
    ],
});

for (const e of entries) {
    fs.writeFileSync(
        path.join(outdir, `${e}.js`),
        `// generated by build-cli.mjs\n` +
            `process.env.NODE_COMPILE_CACHE ??= require('node:path').join(__dirname, '${cacheDir}');\n` +
            `require('node:module').enableCompileCache(process.env.NODE_COMPILE_CACHE);\n` +
            `require('./${e}.bundle.js');\n`,
    );
    // Load as a worker would (a worker waits for its job), then exit, which writes the cache.
    execFileSync(process.execPath, ['-e', `process.send = () => true; require('./${outdir}/${e}.js');`], {
        stdio: 'inherit',
        env: { ...process.env, NODE_COMPILE_CACHE: path.resolve(outdir, cacheDir) },
    });
}
